// First filming walkthrough. Pause-during-blend and resize live in viewer.spec.ts.
import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
await mkdir('.local/filming',{recursive:true});
const browser=await chromium.launch({args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1920,height:1080}});
const origin=process.env.TWIN_TEST_URL||'http://twin-app:8000';
const runs=await (await page.request.get(origin+'/api/runs')).json();const pair=runs.find(r=>r.comparison?.comparison_id)?.comparison;if(!pair)throw new Error('Publish an explicit filming pair first');
if(process.env.TWIN_MLFLOW_TEST_ORIGIN)await page.context().route('http://localhost:5000/**',async route=>{const response=await route.fetch({url:route.request().url().replace('http://localhost:5000',process.env.TWIN_MLFLOW_TEST_ORIGIN)});await route.fulfill({response});});
await page.goto(origin);
await expect(page.locator('#status')).toHaveText('Unity Catalog connected',{timeout:30000});
await page.selectOption('#run',pair.baseline_run_id);
await expect(page.locator('#metrics')).toContainText('peak_pax_A4: 126');
await expect(page.locator('#status')).toHaveText('Unity Catalog connected',{timeout:30000});
await page.screenshot({path:'.local/filming/browser-baseline.png'});
await page.selectOption('#run',pair.delay_run_id);
await expect(page.locator('canvas')).toHaveAttribute('data-blending','true',{timeout:30000});
await page.screenshot({path:'.local/filming/browser-ripple.png'});
await expect(page.locator('#status')).toHaveText('Unity Catalog connected',{timeout:30000});
await expect(page.locator('#metrics')).toContainText('peak_pax_A4: 213');
await page.screenshot({path:'.local/filming/browser-delay.png'});
await page.getByRole('button',{name:'Gate A4 close-up'}).click();
await page.screenshot({path:'.local/filming/browser-a4.png'});
await page.getByRole('button',{name:'Explain A4',exact:true}).click();
await expect(page.locator('#explanation')).toHaveText('213 passengers ≥ critical threshold 180');
await expect(page.locator('#verification')).toContainText('Verified against published Delta versions');
await expect(page.locator('#sensors tr')).toHaveCount(5);
await page.screenshot({path:'.local/filming/browser-provenance.png'});
const popupReady=page.context().waitForEvent('page');await page.locator('#compare').click();const comparison=await popupReady;
await expect(comparison.getByText('peak_pax_A4',{exact:true}).first()).toBeVisible({timeout:30000});
await expect(comparison.locator('body')).toContainText('126');await expect(comparison.locator('body')).toContainText('213');
await comparison.screenshot({path:'.local/filming/mlflow-comparison.png'});
const elapsed=await page.evaluate(()=>{const start=performance.now(),input=document.querySelector('#timeline');input.value='10';input.dispatchEvent(new Event('input'));return performance.now()-start;});
await expect(page.locator('#step')).toHaveText('Minute 10 / 59');
await page.screenshot({path:'.local/filming/browser-minute10.png'});
const evidence={cached_scrub_ms:elapsed,identity:await page.locator('#identity').innerText(),metrics:await page.locator('#metrics').innerText(),renderer:'software Chromium; desktop GPU FPS not measured'};
await writeFile('.local/filming/evidence.json',JSON.stringify(evidence,null,2));
console.log(JSON.stringify(evidence));await page.context().unrouteAll({behavior:'ignoreErrors'});await browser.close();
